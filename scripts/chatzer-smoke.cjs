    await noa.page.click('.sheet [data-a="assign"]')
    await noa.page.waitForSelector('.sheet >> text=למי לתת את')
    await shot(noa, '13a-assign')
    await noa.page.click('.sheet [data-to]:has-text("מאיה")')
    await noa.page.waitForSelector('text=עבר למאיה')
    await noa.page.click('[data-item]:has-text("נייר טואלט")')
    const tomorrow10 = await noa.page.evaluate(() => {
      const d = new Date(Date.now() + 86400e3)
      const p = (n) => String(n).padStart(2, '0')
      return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}T10:00`
    })
    await noa.page.fill('#idue', tomorrow10)
    await noa.page.click('#edit button[type="submit"]')
    await noa.page.waitForSelector('[data-item]:has-text("נייר טואלט") >> text=מחר 10:00')
