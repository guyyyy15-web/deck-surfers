    check(true, 'after joining in the browser: a small guided step to save and install')
    check((await maya.page.$$('.sheet .steps li')).length === 4 && await maya.page.isVisible('.sheet .down-hint'), 'shown in pictures: 4 steps and an arrow down to Safari\'s share button')
    await shot(maya, '06c-after-join')
    await maya.page.click('.sheet-x')
    await maya.page.waitForSelector('.sheet', { state: 'detached' })
    await maya.page.click('.row:has-text("פיתות") [data-claim]')
    await maya.page.waitForSelector('.row.mine:has-text("פיתות")')
    await maya.page.click('.toast button:has-text("בטל")')
    await maya.page.waitForSelector('.row:has-text("פיתות") [data-claim]')
    check(true, '"בטל" right after taking something lets it go again')
    await maya.page.click('.row:has-text("פיתות") [data-claim]')
    await maya.page.waitForSelector('.row.mine:has-text("פיתות")')
    check(true, 'Maya took the pitas (shown as hers)')
    check(/פיתות/.test(await maya.page.textContent('.mine-strip')), '"את מביאה: פיתות" sits on top of the list')
    check(await maya.page.isVisible('.tip'), 'a first tip shows in the yard')
    const tip1 = await maya.page.textContent('.tip')
    await maya.page.click('#tipok')
    await maya.page.goto(APP + '#/')
    await maya.page.click('.yard-card')
    await maya.page.waitForSelector('.row')
    check((await maya.page.textContent('.tip')) !== tip1, '"הבנתי" moves on to the next tip')
    await shot(maya, '07-claimed')

    // 4. Noa sees it; Dani joins; Maya and Dani grab the same item at once: one wins, the other is told.
    await sync(noa)
    check(await noa.page.isVisible('.row:has-text("פיתות") >> text=מאיה'), 'Noa sees that Maya brings the pitas')
    await welcome(dani, 'דני', 'sky', 'm')
    await dani.page.goto(link)
    await dani.page.click('button:has-text("אני בחצר")')
    await dani.page.waitForSelector('.row [data-claim]')
    if (await dani.page.waitForSelector('.sheet >> text=עוד צעד קטן', { timeout: 6000 }).catch(() => null)) await dani.page.click('.sheet-x')
    await dani.page.waitForSelector('.sheet', { state: 'detached' })
    // Dani took nothing yet: Noa (who runs the yard) can remind him.
    await sync(noa)
    await noa.page.click('#nudgefree')
    await noa.page.waitForSelector('.toast >> text=נשלחה תזכורת')
    check(true, 'the admin reminds whoever took nothing yet, in one tap')
    // An item a few people bring together, and an amount typed with the name.
    await noa.page.fill('#addin', 'קולה x3')
    await noa.page.click('#add button[type="submit"]')
    await noa.page.waitForSelector('.row:has-text("קולה") .qty')
    check((await noa.page.textContent('.row:has-text("קולה") .qty')).includes('3'), '"קולה x3" becomes cola, ×3')
    await noa.page.click('.row:has-text("קולה") [data-item]')
    await noa.page.selectOption('.sheet #ineed', '2')
    await noa.page.click('.sheet button[type="submit"]')
    await noa.page.waitForSelector('.sheet', { state: 'detached' })
    await sync(maya)
    await sync(dani)
    await maya.page.click('.row:has-text("קולה") [data-claim]')
    await maya.page.waitForSelector('.row.mine:has-text("קולה")')
    check(await maya.page.isVisible('.joy'), 'taking something: the duckling hops for joy')
    await sync(dani)
    check((await dani.page.textContent('.row:has-text("קולה") [data-claim]')).includes('גם אני'), 'the cola needs two: Dani is offered "גם אני!"')
    await dani.page.click('.row:has-text("קולה") [data-claim]')
    await dani.page.waitForSelector('.row.mine:has-text("קולה")')
    await sync(noa)
    check(/מאיה \+ דני · 2\/2/.test(await noa.page.textContent('.row:has-text("קולה")')) && !(await noa.page.$('.row:has-text("קולה") [data-claim]')), 'Maya and Dani bring the cola together, and it counts as taken')
    await sync(maya)
    await Promise.all([
      maya.page.click('.row:has-text("חומוס") [data-claim]'),
      dani.page.click('.row:has-text("חומוס") [data-claim]'),
    ])
    await wait(1500)
    await sync(maya)
    await sync(dani)
    const mayaHas = await maya.page.isVisible('.row.mine:has-text("חומוס")')
    const daniHas = await dani.page.isVisible('.row.mine:has-text("חומוס")')
    check(mayaHas !== daniHas, `a race for the hummus has exactly one winner (${mayaHas ? 'Maya' : 'Dani'})`)
    if (mayaHas) {
      await dani.page.click('.row:has-text("חומוס") .what')
      check(await dani.page.waitForSelector('.sheet >> text=מאיה מביאה', { timeout: 5000 }).catch(() => null), 'Dani reads "מאיה מביאה" (her form of address)')
    } else {
      await maya.page.click('.row:has-text("חומוס") .what')
      check(await maya.page.waitForSelector('.sheet >> text=דני מביא', { timeout: 5000 }).catch(() => null), 'Maya reads "דני מביא" (his form of address)')
    }
    await (mayaHas ? dani : maya).page.goBack()

    // 5. Adding an item, a poll, chat.
    await noa.page.fill('#addin', 'מלח גס')
    await noa.page.click('#add button[type="submit"]')
    await noa.page.waitForSelector('.row:has-text("מלח גס")')
    await noa.page.fill('#addin', 'קרח, מחצלות, נרות')
    await noa.page.click('#add button[type="submit"]')
    await noa.page.waitForSelector('.row:has-text("נרות")')
    check(await noa.page.isVisible('.row:has-text("קרח")') && await noa.page.isVisible('.row:has-text("מחצלות")'), 'a list typed at once became 3 items')
    await noa.page.click('.toast button:has-text("בטל")')
    await noa.page.waitForSelector('.row:has-text("נרות")', { state: 'detached' })
    check(!(await noa.page.isVisible('.row:has-text("מחצלות")')), 'and "בטל" took all 3 back')
    // The summary for WhatsApp, the calendar, and "one more like this".
    await noa.page.click('#share')
    await noa.page.waitForSelector('.sheet .summary')
    await noa.page.waitForFunction(() => /לוקחים כאן: http/.test(document.querySelector('.summary')?.textContent || ''), null, { timeout: 10000 })
    const summary = await noa.page.textContent('.summary')
    check(/✅ פיתות: מאיה/.test(summary) && /⬜ .+: עוד פנוי/.test(summary), 'the WhatsApp summary lists who brings what, what is free, and a link')
    check((await noa.page.getAttribute('#wa', 'href')).startsWith('https://wa.me/?text='), 'and opens WhatsApp with it')
    await shot(noa, '09a-summary')
    await noa.page.click('.sheet-x')
    await noa.page.click('#menu')
    await noa.page.click('.sheet [data-a="calendar"]')
    await noa.page.waitForSelector('.sheet #ics')
    check((await noa.page.getAttribute('#ics', 'href')).startsWith('blob:') && (await noa.page.getAttribute('.sheet a[href^="https://calendar.google.com"]', 'href')).includes('action=TEMPLATE'), 'the event goes to the calendar (a file, or Google Calendar)')
    await noa.page.click('.sheet-x')
    await noa.page.click('#menu')
    await noa.page.click('.sheet [data-a="again"]')
    await noa.page.waitForSelector('.sheet >> text=עוד אחד כזה')
    await noa.page.waitForFunction(() => document.querySelectorAll('.sheet [data-own]').length >= 10, null, { timeout: 5000 })
    check((await noa.page.inputValue('#yname')) === 'מנגל שישי אצל הילה', '"one more like this" starts from the same name and the same list')
    await noa.page.click('.sheet-x')
    await noa.page.click('#poll')
    await noa.page.fill('#q', 'מתי מתחילים?')
    const opts = await noa.page.$$('#opts input')
    await opts[0].fill('13:00')
    await opts[1].fill('14:00')
    await noa.page.click('button:has-text("שליחה לחצר")')
    await noa.page.waitForSelector('.poll')
    await sync(maya)
    await maya.page.click('.opt:has-text("14:00")')
    await maya.page.waitForSelector('.opt[aria-pressed="true"]:has-text("14:00")')
    check(true, 'Maya voted in Noa’s poll')
    await maya.page.click('a:has-text("צ׳אט")')
    await maya.page.fill('#msg', 'מישהו מביא מחצלות?')
    await maya.page.click('#f button[type="submit"]')
    await maya.page.waitForSelector('.bubble:has-text("מחצלות")')
    await noa.page.goto(`${APP}#/y/${link ? (await noa.page.evaluate(() => location.hash.split('/')[2])) : ''}/chat`)
    await noa.page.waitForSelector('.bubble:has-text("מחצלות")', { timeout: 15000 })
    check(true, 'Noa reads Maya’s chat message')
    await shot(noa, '08-chat')
    // Dani reports Maya's message; Noa (who runs the yard) sees a banner and deletes it.
    await dani.page.goto(`${APP}#/y/${await noa.page.evaluate(() => location.hash.split('/')[2])}/chat`)
    await dani.page.waitForSelector('.bubble:has-text("מחצלות")', { timeout: 15000 })
    await dani.page.click('.msg:has-text("מחצלות") [data-msg]')
    await dani.page.click('#rep')
    await dani.page.waitForSelector('text=הדיווח נשלח')
    check(true, 'Dani reported a message to the admin')
    await noa.page.goBack()
    await sync(noa)
    await noa.page.waitForSelector('#reports', { timeout: 15000 })
    check(true, 'Noa (admin) sees "1 open report"')
    await noa.page.click('#reports')
    await noa.page.waitForSelector('.sheet >> text=מחצלות')
    await shot(noa, '08b-reports')
    await noa.page.click('.sheet [data-remove]')
    await noa.page.waitForSelector('#reports', { state: 'detached', timeout: 15000 })
    await sync(dani)
    check(!(await dani.page.isVisible('.bubble:has-text("מחצלות")')), 'the admin deleted it, for everyone')
    await noa.page.goto(`${APP}#/y/${await noa.page.evaluate(() => location.hash.split('/')[2])}/chat`)
    await noa.page.goBack()
    await noa.page.waitForSelector('.poll')
    await shot(noa, '09-event-full')

    // 6. A home yard: chores in turns, done passes the turn on.
    await noa.page.goto(APP)
    await noa.page.click('[data-new="home"]')
    await noa.page.waitForSelector('#yname')
    await noa.page.fill('#yname', 'הדירה')
    check(!(await noa.page.isVisible('[data-chore]:has-text("טיול עם הכלב")')), 'no pet yet: no dog chores')
    await noa.page.click('.sheet [data-pet="dog"]')
    check(await noa.page.isVisible('[data-chore]:has-text("טיול עם הכלב")') && await noa.page.isVisible('[data-chore]:has-text("ניקיון שירותים ואמבטיה")'), 'with a dog: dog chores are offered, next to the house ones')
    check(!(await noa.page.isVisible('[data-chore]:has-text("ניקוי ארגז החול")')), 'no cat, no litter box')
    await noa.page.fill('#cchore', 'להאכיל את הדגים')
    await noa.page.press('#cchore', 'Enter')
    await noa.page.waitForSelector('[data-own]:has-text("להאכיל את הדגים")')
    await shot(noa, '10a-new-home-yard')
    await noa.page.click('button:has-text("פותחים חצר")')
    await noa.page.waitForFunction(() => /join/.test(document.querySelector('#link')?.textContent || ''), null, { timeout: 15000 })
    const homeLink = (await noa.page.textContent('#link')).trim()
    await noa.page.click('.sheet-x')
    await noa.page.waitForSelector('.sheet', { state: 'detached' })
    check(true, 'the close button closes the popup')
    await noa.page.waitForSelector('.turn-card')
    check((await noa.page.$$('.turn-card')).length === 4 && (await noa.page.isVisible('.turn-card:has-text("להאכיל את הדגים")')), 'the one who opened the home yard starts all 4 chores, including her own')
    await shot(noa, '10-home-yard')
    await maya.page.goto(homeLink)
    await maya.page.click('button:has-text("אני בחצר")')
    await maya.page.waitForSelector('text=מטלות בתורות')
    await sync(noa)
    await noa.page.click('.turn-card:has-text("שטיפת כלים") [data-cdone]')
    await noa.page.waitForSelector('text=תמונת הוכחה זה לא חובה')
    await shot(noa, '11-done-sheet')
    await noa.page.click('#ok')
    await noa.page.waitForSelector('text=כל הכבוד')
    check((await noa.page.$$('.turn-card')).length === 3 && !(await noa.page.isVisible('.turn-card:has-text("שטיפת כלים")')), 'after "done", the dishes are no longer Noa’s turn')
    await sync(maya)
    // Done today, daily: Maya's turn is tomorrow (the big card shows on the day it is due).
