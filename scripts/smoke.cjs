// End-to-end smoke test on an iPhone 15 viewport, then an iPhone SE layout pass.
// Starts its own server, walks through every screen, and writes screenshots to screenshots/.
//   node scripts/smoke.cjs
const { chromium, devices } = require('playwright')
const { spawn } = require('child_process')
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const OUT = path.join(ROOT, 'screenshots')
const PORT = 8765
const URL_ = `http://localhost:${PORT}/`
fs.mkdirSync(OUT, { recursive: true })

const check = (cond, msg) => {
  if (!cond) throw new Error(`FAIL: ${msg}`)
  console.log(`ok  ${msg}`)
}

;(async () => {
  const server = spawn(process.execPath, [path.join(__dirname, 'serve.cjs'), String(PORT)], { stdio: 'ignore' })
  await new Promise((r) => setTimeout(r, 400))
  const browser = await chromium.launch()
  try {
    // Test photos: the sample face from the design, and a "documentation" picture.
    const maker = await browser.newPage()
    const face = async (svg, w, h) => {
      await maker.setViewportSize({ width: w, height: h })
      await maker.setContent(`<style>html,body{margin:0}</style>${svg}`)
      return maker.screenshot({ type: 'png' })
    }
    const FACE = await face(`<svg width="600" height="700" viewBox="0 0 260 300"><rect width="260" height="300" fill="#f4e7f1"/><path d="M0 230 Q60 200 130 214 Q200 200 260 230 L260 300 L0 300z" fill="#c9a3dd"/><circle cx="130" cy="124" r="58" fill="#f4a9c4"/><path d="M74 120 Q76 56 130 56 Q186 56 186 120 Q170 92 130 90 Q92 92 74 120z" fill="#3a2340"/><path d="M70 300 Q76 196 130 196 Q184 196 190 300z" fill="#7f4fa0"/><path d="M108 128 q6 -6 12 0 M140 128 q6 -6 12 0 M116 150 q14 10 28 0" stroke="#3a2340" stroke-width="4" stroke-linecap="round" fill="none"/></svg>`, 600, 700)
    const DOC = await face(`<svg width="800" height="600"><rect width="800" height="600" fill="#e6d0ef"/><circle cx="600" cy="160" r="80" fill="#f2c14e"/><path d="M0 600 L250 300 L420 480 L560 360 L800 600z" fill="#7f4fa0"/><text x="40" y="90" font-size="60" fill="#3a2340">🎂 סליחה!</text></svg>`, 800, 600)
    await maker.close()
    const file = (name, buffer) => ({ name, mimeType: 'image/png', buffer })

    const context = await browser.newContext({ ...devices['iPhone 15'], locale: 'he-IL', timezoneId: 'Asia/Jerusalem', acceptDownloads: true })
    const page = await context.newPage()
    const errors = []
    page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
    page.on('pageerror', (e) => errors.push(String(e)))
    const shot = (name) => page.screenshot({ path: path.join(OUT, `${name}.png`) })
    const noSideScroll = async (where) => {
      const ok = await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
      check(ok, `${where}: no sideways scrolling`)
    }
    const toastText = async () => (await page.locator('.toast').textContent()) || ''

    // 1. Splash, then the empty home screen.
    await page.goto(URL_)
    check(await page.isVisible('#splash'), 'splash screen shows on launch')
    await page.waitForTimeout(350)
    await shot('01-splash')
    await page.waitForSelector('#splash', { state: 'detached' })
    check(await page.isVisible('.empty'), 'home: empty state with the cat')
    check(await page.isVisible('.banner'), 'home: iPhone install hint in Safari')
    await shot('02-home-empty')
    await page.click('[data-act="hide-install"]')
    check(!(await page.isVisible('.banner')), 'install hint can be dismissed')

    check(!(await page.isVisible('.nk-fab')), 'empty home: no floating +, an inline button instead')
    // 2. New revenge: validation, photo + crop, fields, save.
    await page.click('.empty .nk-btn')
    await page.waitForSelector('form')
    check((await page.textContent('h1')) === 'נקמה חדשה', 'FAB opens "new revenge"')
    await page.click('[type=submit]')
    check((await page.locator('.nk-field.has-error').count()) === 2, 'required fields show errors')
    await page.setInputFiles('[data-face]', file('face.png', FACE))
    await page.waitForSelector('.crop-stage img')
    await page.waitForTimeout(200)
    const stage = await page.locator('.crop-stage').boundingBox()
    await page.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2)
    await page.mouse.down()
    await page.mouse.move(stage.x + stage.width / 2 + 30, stage.y + stage.height / 2 + 60, { steps: 5 })
    await page.mouse.up()
    await page.locator('#zoom').fill('160')
    await page.waitForTimeout(100)
    check((await page.textContent('[data-zl]')) === '160%', 'crop: zoom slider')
    await shot('04-crop')
    await page.click('[data-ok]')
    await page.waitForSelector('.photo-ring.has-img img')
    check(!(await page.isVisible('.crop-stage')), 'crop: saving returns to the form with the photo')
    await page.fill('#f-name', 'רונית מהחשבות')
    await page.fill('#f-why', 'הוציאה לי את החשק לחיות. שלחה מייל לכל המחלקה על הדוח שלי, עם העתק לבוס.')
    await page.click('[data-type="cruel"]')
    check((await page.getAttribute('[data-type="cruel"]', 'aria-checked')) === 'true', 'type picker selects')
    const in5 = await page.evaluate(() => { const d = new Date(); d.setDate(d.getDate() + 5); return d.toISOString().slice(0, 10) })
    await page.fill('#f-date', in5)
    check(!(await page.isVisible('.date-ph')), 'date placeholder hides once a date is picked')
    await shot('03-new')
    await page.click('[type=submit]')
    await page.waitForSelector('.nk-card')
    check((await toastText()).includes('נרשמה'), 'saved, with a toast')

    // Two more: one plain, one from an idea.
    const add = async (name, why, type) => {
      await page.click('.nk-fab')
      await page.fill('#f-name', name)
      await page.fill('#f-why', why)
      if (type) await page.click(`[data-type="${type}"]`)
      await page.click('[type=submit]')
      await page.waitForSelector(`.nk-card-title:text("${name}")`)
    }
    await add('דני החניה', 'תופס לי כל פעם את המקום', 'small')
    await add('השליח', 'הביא שוב בלי רוטב!')
    check((await page.locator('.nk-card').count()) === 3, 'home: three open revenges')
    check((await page.textContent('.nk-tab.is-on')).includes('(3)'), 'tab shows the count')
    check((await page.locator('.avatar-face img').count()) === 1, 'the photo shows in the avatar')
    check((await page.locator('.due').count()) === 1, 'the reminder shows on the card')
    await page.waitForTimeout(300)
    await shot('05-home')
    await noSideScroll('home')

    // 3. Details + calendar reminder.
    await page.click('.nk-card-title:text("רונית מהחשבות")')
    await page.waitForSelector('.hero')
    check((await page.textContent('.chip')).startsWith('פתוחה · נפתחה ב-'), 'details: status chip')
    await page.waitForTimeout(200)
    await shot('06-details')
    const [ics] = await Promise.all([page.waitForEvent('download'), page.click('[data-act="ics"]')])
    const icsText = fs.readFileSync(await ics.path(), 'utf8')
    check(icsText.includes(`DTSTART;VALUE=DATE:${in5.replace(/-/g, '')}`), 'calendar reminder file for the iPhone calendar')

    // 4. Edit.
    await page.click('[aria-label="עריכה"]')
    await page.waitForSelector('form')
    check((await page.inputValue('#f-name')) === 'רונית מהחשבות', 'edit form is filled in')
    await page.fill('#f-plan', 'להדפיס את המייל שלה ולתלות במטבחון עם תיקונים באדום')
    await page.click('[type=submit]')
    await page.waitForSelector('.hero')
    check((await page.textContent('.info')).includes('התוכנית'), 'edit saved (plan shows)')

    // 5. Complete from the home list, with notes and a documentation photo.
    await page.click('a[aria-label="חזרה"]')
    await page.click('.nk-card:has-text("דני החניה") .nk-check')
    await page.waitForSelector('.sheet')
    await page.fill('#c-notes', 'שמתי לו קונוסים על המקום. הוא חנה ברחוב הבא 😇')
    await page.setInputFiles('.pick-tile:nth-child(2) input', file('doc.png', DOC))
    await page.waitForSelector('.doc-preview img')
    await shot('07-complete')
    await page.click('[data-save]')
    await page.waitForSelector('.sheet', { state: 'detached' })
    await page.waitForTimeout(450)
    check((await page.locator('.nk-card').count()) === 2, 'completed revenge leaves the open list')
    check((await toastText()).includes('להיסטוריה'), 'toast with undo after completing')
    // Undo, then complete again with "skip".
    await page.click('.toast button')
    await page.waitForTimeout(200)
    check((await page.locator('.nk-card').count()) === 3, 'undo brings it back')
    await page.click('.nk-card:has-text("השליח") .nk-check')
    await page.click('[data-skip]')
    await page.waitForTimeout(450)
    await page.click('.nk-card:has-text("דני החניה") .nk-check')
    await page.fill('#c-notes', 'קונוסים. הרבה קונוסים.')
    await page.setInputFiles('.pick-tile:nth-child(1) input', file('doc.png', DOC))
    await page.waitForSelector('.doc-preview img')
    await page.click('[data-save]')
    await page.waitForTimeout(450)

    // 6. History and a done revenge.
    await page.click('.nk-tab:has-text("שהושלמו")')
    await page.waitForSelector('.month')
    check((await page.locator('.month').count()) === 1, 'history: grouped by month')
    check((await page.locator('.thumb img').count()) === 1, 'history: documentation thumbnail')
    await page.waitForTimeout(250)
    await shot('08-history')
    await page.click('.nk-card:has-text("דני החניה")')
    await page.waitForSelector('.chip.ok')
    check((await page.textContent('.info')).includes('קונוסים'), 'done details: notes')
    await page.waitForSelector('.doc-img img[src]')
    await page.waitForTimeout(200)
    await shot('09-done-details')
    await noSideScroll('done details')

    // 7. Stats and ideas.
    await page.goto(`${URL_}#/stats`)
    await page.waitForSelector('#splash', { state: 'detached' })
    await page.waitForSelector('.stat-grid')
    check((await page.textContent('.stat-grid')).includes('67%'), 'stats: completion rate')
    await shot('10-stats')
    await page.click('.nk-nav-item:has-text("השראה")')
    await page.waitForSelector('.idea-lucky')
    const first = await page.textContent('.idea-lucky .t')
    await page.click('[data-act="lucky"]')
    check((await page.textContent('.idea-lucky .t')) !== first, 'ideas: "another idea" changes it')
    await page.click('[data-filter="small"]')
    check((await page.locator('.idea').count()) >= 5, 'ideas: filter by type')
    await page.click('[data-filter="all"]')
    await shot('11-ideas')
    await page.click('.idea >> nth=0 >> a')
    await page.waitForSelector('form')
    check((await page.inputValue('#f-plan')).length > 10, 'an idea fills the plan of a new revenge')
    await page.click('a[aria-label="חזרה"]')

    // 8. Settings: masculine wording, dark mode.
    await page.click('[aria-label="הגדרות"]')
    await page.waitForSelector('.seg')
    await page.waitForTimeout(400)
    await shot('12-settings')
    await page.click('[data-set="voice"][data-val="m"]')
    await page.goto(`${URL_}#/new`)
    check((await page.textContent('[type=submit]')).includes('שמור נקמה'), 'masculine wording: "שמור נקמה"')
    await page.goto(`${URL_}#/settings`)
    await page.click('[data-set="voice"][data-val="f"]')
    await page.click('[data-set="theme"][data-val="dark"]')
    check((await page.getAttribute('html', 'data-theme')) === 'dark', 'dark mode switch')
    await page.goto(URL_)
    await page.waitForSelector('#splash', { state: 'detached' })
    await page.waitForSelector('.nk-card')
    await page.waitForTimeout(300)
    await shot('13-home-dark')
    await page.click('.nk-card-title:text("רונית מהחשבות")')
    await page.waitForTimeout(300)
    await shot('14-details-dark')
    await page.goto(`${URL_}#/settings`)
    await page.click('[data-set="theme"][data-val="light"]')

    // 9. Backup: export, wipe, import.
    const [dl] = await Promise.all([page.waitForEvent('download'), page.click('[data-act="export"]')])
    const backupPath = path.join(OUT, '..', 'node_modules_backup_test.json')
    await dl.saveAs(backupPath)
    const backup = JSON.parse(fs.readFileSync(backupPath, 'utf8'))
    check(backup.revenges.length === 3 && backup.photos.length === 2, 'export: 3 revenges and 2 photos')
    await page.click('[data-act="wipe"]')
    await page.click('[data-ok]')
    await page.waitForSelector('.empty')
    check((await page.locator('.nk-card').count()) === 0, 'wipe: everything deleted')
    await page.goto(`${URL_}#/settings`)
    await page.setInputFiles('[data-import]', backupPath)
    await page.waitForSelector('.toast:has-text("יובאו")')
    check((await toastText()).includes('יובאו 3'), 'import: 3 revenges restored')
    fs.unlinkSync(backupPath)
    await page.goto(`${URL_}#/done`)
    await page.waitForSelector('.thumb img[src]')
    check(true, 'import: photos restored')

    // 10. Delete with undo.
    await page.goto(URL_)
    await page.click('.nk-card-title:text("רונית מהחשבות")')
    await page.click('[data-act="delete"]')
    await page.click('[data-ok]')
    await page.waitForSelector('.toast')
    check((await page.locator('.nk-card').count()) === 0, 'delete removes it')
    await page.click('.toast button')
    await page.waitForSelector('.nk-card')
    check((await page.locator('.nk-card').count()) === 1, 'delete can be undone')

    // 11. Offline: reload with no network.
    await page.evaluate(() => navigator.serviceWorker.ready)
    await page.reload()
    await page.waitForSelector('.nk-card')
    await context.setOffline(true)
    await page.reload()
    await page.waitForSelector('.nk-card', { timeout: 8000 })
    check((await page.locator('.nk-card').count()) === 1, 'offline: the app and its data load with no network')
    const fontsOk = await page.evaluate(async () => { await document.fonts.ready; return document.fonts.check('600 20px Fredoka', 'נקמות') })
    check(fontsOk, 'offline: the fonts load from the cache')
    await context.setOffline(false)

    check(errors.length === 0, `no console errors${errors.length ? `: ${errors.join(' | ')}` : ''}`)
    await context.close()

    // 12. iPhone SE: the smallest screen still fits.
    const se = await browser.newContext({ ...devices['iPhone SE'], locale: 'he-IL' })
    const p2 = await se.newPage()
    await p2.goto(`${URL_}#/new`)
    await p2.waitForSelector('form')
    await p2.waitForSelector('#splash', { state: 'detached' })
    await p2.waitForTimeout(300)
    const fits = await p2.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)
    check(fits, 'iPhone SE: new-revenge form fits the width')
    await p2.screenshot({ path: path.join(OUT, '15-se-new.png') })
    await se.close()
    console.log('\nall good')
  } finally {
    await browser.close()
    server.kill()
  }
})().catch((e) => {
  console.error(e)
  process.exit(1)
})
